import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'
import { mailLink } from './mailpit'

test('private debts flow through repayment, edits, dashboard balances, and history', async ({ page, request }) => {
  test.setTimeout(75_000)
  await page.goto('/debts')
  await expect(page.getByRole('link', { name: 'Sign in' })).toBeVisible()

  const username = 'debt_' + Date.now().toString(36)
  const email = username + '@example.test'
  await page.goto('/account/signup')
  await page.getByLabel('Name in Arabic').fill('سلمى')
  await page.getByLabel('Name in English').fill('Salma')
  await page.getByLabel('Username').fill(username)
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password', { exact: true }).fill('Spend-test-2026!')
  await page.getByLabel('Confirm password').fill('Spend-test-2026!')
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByRole('status')).toContainText('will arrive shortly')
  await page.goto(await mailLink(request, email, '/account/confirm'))
  await page.getByRole('button', { name: 'Verify link' }).click()
  await expect(page.getByRole('status')).toHaveText('Email confirmed.')

  await page.goto('/overview')
  await page.getByRole('link', { name: 'Private debts' }).click()
  await page.getByRole('button', { name: 'Add debt', exact: true }).click()
  const entry = page.locator('.debt-entry')
  const detail = page.locator('.debt-detail')
  const history = page.locator('.debt-history')
  await entry.getByLabel('Contact name').fill('علي')
  await entry.getByLabel('Total amount (EGP)').fill('٢٠٠')
  await entry.getByLabel('Due date (optional)').fill('2030-01-15')
  await entry.getByRole('button', { name: 'Save debt' }).click()
  await expect(detail.getByRole('heading', { level: 2 })).toContainText('علي')
  const debtPath = new URL(page.url()).pathname + new URL(page.url()).search

  const repayment = detail.getByLabel('Payment amount (EGP)')
  await repayment.fill('201')
  await detail.getByRole('button', { name: 'Record payment' }).click()
  await expect(page.getByRole('alert')).toContainText('remaining balance')
  await repayment.fill('٧٥٫٥٠')
  await detail.getByRole('button', { name: 'Record payment' }).click()
  await expect(detail.locator('.debt-balances')).toContainText('124.5')
  await expect(detail.locator('.debt-payments')).toContainText('75.5')
  await expect(history).toContainText('Payment recorded')

  await detail.getByRole('button', { name: 'Edit debt' }).click()
  await expect(entry.getByLabel('Contact name')).toBeFocused()
  await entry.getByLabel('Total amount (EGP)').fill('225')
  await entry.getByRole('button', { name: 'Save debt' }).click()
  await expect(detail.locator('.debt-balances')).toContainText('149.5')
  await expect(history).toContainText('Debt updated')

  await page.goto('/overview')
  await expect(page.locator('.metric').filter({ hasText: 'Owed to me' })).toContainText('149.5')
  await expect(page.locator('.metric').filter({ hasText: 'Spent this month' })).toContainText('EGP 0')
  const due = page.locator('.follow-up').getByRole('link').filter({ hasText: 'علي' })
  await expect(due).toHaveAttribute('href', debtPath)
  await due.click()
  await repayment.fill('149.50')
  await detail.getByRole('button', { name: 'Record payment' }).click()
  await expect(detail.getByText('Settled', { exact: true })).toBeVisible()
  await expect(repayment).toHaveCount(0)

  await page.setViewportSize({ width: 390, height: 850 })
  await page.locator('.language').selectOption('ar')
  await page.locator('.theme-toggle').click()
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await detail.getByRole('button', { name: 'أرشفة الدين' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'تأكيد الأرشفة' }).click()
  await expect(detail).toHaveCount(0)
  await expect(history).toContainText('الدين اتأرشف')
  await expect(history).toContainText('الدفعة اتسجّلت')
})
