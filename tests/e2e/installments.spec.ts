import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'
import { mailLink } from './mailpit'
import { pickDate } from './date-picker'

test('installments track partial and full payments, dashboard balances, and history', async ({ page, request }) => {
  test.setTimeout(75_000)
  await page.goto('/installments')
  await expect(page.getByRole('link', { name: 'Sign in' })).toBeVisible()
  const username = 'plan_' + Date.now().toString(36)
  const email = username + '@example.test'
  await page.goto('/account/signup')
  await page.getByLabel('Name in Arabic').fill('سلمى')
  await page.getByLabel('Name in English').fill('Salma')
  await page.getByLabel('Username').fill(username)
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password', { exact: true }).fill('Spend-test-2026!')
  await page.getByLabel('Confirm password').fill('Spend-test-2026!')
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByRole('status')).toContainText('will arrive shortly')
  await page.goto(await mailLink(request, email, '/account/confirm'))
  await page.getByRole('button', { name: 'Verify link' }).click()
  await expect(page.getByRole('status')).toHaveText('Email confirmed.')

  await page.goto('/overview')
  await page.getByRole('link', { name: 'Installments', exact: true }).click()
  await page.getByRole('button', { name: 'New installment plan', exact: true }).click()
  const entry = page.locator('.installment-entry')
  const detail = page.locator('.installment-detail')
  const history = page.locator('.installment-history')
  await entry.getByLabel('Plan name').fill('Laptop')
  await entry.getByLabel('Plan total').fill('١٠٠')
  await pickDate(page, entry.getByRole('button', { name: /^Due date/ }), 'Due date', '2000-01-01')
  await entry.getByLabel('Installment amount').fill('60')
  await entry.getByRole('button', { name: 'Save plan' }).click()
  await expect(page.getByRole('alert')).toContainText('add up')
  await entry.getByRole('button', { name: 'Add installment' }).click()
  await pickDate(page, entry.getByRole('button', { name: /^Due date/ }).nth(1), 'Due date', '2099-01-01')
  await entry.getByLabel('Installment amount').nth(1).fill('40')
  await entry.getByRole('button', { name: 'Save plan' }).click()
  await expect(detail.getByRole('heading', { level: 2 })).toHaveText('Laptop')
  await detail.getByLabel('Show installments').selectOption('installmentOverdue')
  const overdue = detail.locator('.installment-dues > li')
  await expect(overdue).toHaveCount(1)
  const nextPayment = detail.locator('.installment-next').getByRole('button', { name: 'Record payment' })
  const payment = page.getByRole('dialog', { name: 'Record payment' })
  await nextPayment.click()
  await payment.getByLabel('Payment amount (EGP)').fill('20')
  await payment.getByRole('button', { name: 'Record payment' }).click()
  await expect(overdue).toContainText('Remaining · EGP 40')
  await nextPayment.click()
  await payment.getByLabel('Payment amount (EGP)').fill('41')
  await payment.getByRole('button', { name: 'Record payment' }).click()
  await expect(page.getByRole('alert')).toContainText('remaining balance')
  await payment.getByLabel('Payment amount (EGP)').fill('40')
  await payment.getByRole('button', { name: 'Record payment' }).click()
  await expect(detail).toContainText('No installments match this filter.')
  await detail.getByLabel('Show installments').selectOption('installmentPaid')
  await expect(detail.locator('.installment-dues > li')).toHaveCount(1)
  const planPath = new URL(page.url()).pathname + new URL(page.url()).search
  await detail.getByRole('link', { name: 'Back to plans' }).click()
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await expect(history.getByText('Payment recorded', { exact: false })).toHaveCount(2)
  await page.goto('/overview')
  await expect(page.locator('.metric').filter({ hasText: 'Spent this month' })).toContainText('EGP 0')
  const overview = page.locator('.installment-overview')
  await expect(overview.locator('dl > div').filter({ hasText: 'Paid this month' })).toContainText('EGP 60')
  await expect(overview.locator('dl > div').filter({ hasText: 'Outstanding balance' })).toContainText('EGP 40')
  await expect(overview.locator('dl > div').filter({ hasText: 'Overdue balance' })).toContainText('EGP 0')
  await expect(overview.getByRole('link', { name: /Laptop/ })).toHaveAttribute('href', planPath)

  await page.goto(planPath)
  await page.setViewportSize({ width: 390, height: 850 })
  await page.locator('.language').selectOption('ar')
  await page.locator('.theme-toggle').click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await detail.getByRole('button', { name: 'أرشفة الخطة' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'تأكيد الأرشفة' }).click()
  await expect(detail.getByText('الخطة اتأرشفت')).toBeVisible()
  await detail.locator('.debt-back').click()
  await page.getByRole('button', { name: 'السجل', exact: true }).click()
  await expect(history.getByText('الدفعة اتسجّلت', { exact: false })).toHaveCount(2)

  await page.goto('/overview')
  await page.locator('.nav-more').click()
  await page.getByRole('dialog').getByRole('link', { name: 'الأقساط', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'الأقساط', exact: true })).toBeVisible()
})
