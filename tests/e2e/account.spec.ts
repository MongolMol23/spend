import { expect, test } from '@playwright/test'
import { mailLink } from './mailpit'

test('public signup, email confirmation, language preference and password recovery', async ({ page, request }) => {
  test.setTimeout(60_000)
  const id = Date.now().toString(36)
  const email = 'spend-' + id + '@example.com'
  const password = 'Spend-test-2026!'
  const newPassword = 'Spend-test-new-2026!'

  await page.goto('/overview#request')
  await expect(page.getByRole('heading', { name: 'Your personal ledger' })).toBeVisible()
  await expect(page.locator('.metric')).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Sample request' })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Sign in' })).toHaveAttribute('href', '/account')
  await page.getByRole('banner').getByRole('link', { name: 'Spend' }).click()
  await expect(page).toHaveURL('/')
  await expect(page.getByRole('heading', { name: 'Keep track of your money' })).toBeVisible()
  await expect(page.locator('.metric')).toHaveCount(0)
  await page.getByRole('link', { name: 'Create account' }).click()
  await page.getByLabel('Name in Arabic').fill('محمد')
  await page.getByLabel('Name in English').fill('Mohamed')
  await page.getByLabel('Username').fill('Spend_' + id)
  await expect(page.locator('#signup-username-available')).toHaveText('Username available.')
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByLabel('Confirm password').fill('Does-not-match')
  await page.getByLabel('Confirm password').blur()
  await expect(page.locator('#account-confirm_password-error')).toHaveText('The passwords do not match.')
  await page.getByLabel('Confirm password').fill(password)
  await expect(page.locator('#account-confirm_password-error')).toHaveCount(0)
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByRole('status')).toContainText('will arrive shortly')
  await page.reload()
  const username = page.getByLabel('Username')
  await username.fill('SPEND_' + id)
  await expect(page.locator('#account-username-error')).toHaveText('That username is already taken.')
  await expect(username).toHaveAttribute('aria-invalid', 'true')
  await username.fill('spend_new_' + id)
  await expect(page.locator('#signup-username-available')).toHaveText('Username available.')
  await expect(username).not.toHaveAttribute('aria-invalid', 'true')
  await page.goto(await mailLink(request, email, '/account/confirm'))
  await page.getByRole('button', { name: 'Verify link' }).click()
  await expect(page.getByRole('status')).toHaveText('Email confirmed.')
  await page.getByRole('link', { name: 'Sign in' }).click()

  await expect(page.getByLabel('Username', { exact: true })).toHaveValue('spend_' + id)
  await expect(page.getByLabel('Name in Arabic')).toHaveValue('محمد')
  await expect(page.getByLabel('Name in English')).toHaveValue('Mohamed')
  await page.locator('.language').selectOption('ar')
  const profileSignOut = page.getByRole('main').getByRole('button', { name: 'تسجيل الخروج' })
  await expect(profileSignOut).toBeVisible()
  await page.reload()
  await expect(profileSignOut).toBeVisible()
  await expect(page.locator('.language')).toHaveValue('ar')
  await page.locator('.language').selectOption('en')
  await expect(page.locator('html')).toHaveAttribute('dir', 'ltr')
  await expect(page.locator('select[name=language]')).toHaveCount(0)
  await page.getByLabel('Name in Arabic').fill('أحمد')
  await page.getByLabel('Name in English').fill('Ahmed')
  await page.getByRole('button', { name: 'Save profile' }).click()
  await expect(page.getByRole('status')).toHaveText('Profile saved.')
  await expect(page.getByRole('heading', { name: 'Ahmed', exact: true })).toBeVisible()
  await page.locator('.language').selectOption('ar')
  await expect(page.getByRole('status')).toHaveText('بيانات حسابك اتحفظت.')
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl')
  await page.reload()
  await expect(page.getByLabel('اسم المستخدم', { exact: true })).toHaveValue('spend_' + id)
  await expect(page.getByRole('heading', { name: 'أحمد', exact: true })).toBeVisible()
  await expect(page.getByLabel('الاسم بالإنجليزي')).toHaveValue('Ahmed')
  await expect(page.locator('.profile-member time')).toHaveAttribute('datetime', /^\d{4}-\d{2}-\d{2}T/)
  await page.getByRole('button', { name: 'غيّر كلمة السر' }).click()
  await expect(page.getByRole('status')).toHaveText('شوف إيميلك عشان تلاقي لينك تغيير كلمة السر.')
  await page.goto(await mailLink(request, email, '/account/reset'))
  await page.getByRole('button', { name: 'تأكيد اللينك' }).click()
  await page.getByLabel('كلمة السر', { exact: true }).fill(newPassword)
  await page.getByRole('button', { name: 'اختار كلمة سر جديدة' }).click()
  await expect(page.getByRole('status')).toHaveText('كلمة السر اتغيّرت. تقدر تسجّل دخولك.')
  await page.goto('/overview')
  await page.getByRole('link', { name: 'تسجيل الدخول' }).click()
  await page.getByLabel('الإيميل').fill(email)
  await page.getByLabel('كلمة السر', { exact: true }).fill(newPassword)
  await page.getByRole('button', { name: 'تسجيل الدخول' }).click()
  await expect(page.getByRole('heading', { name: 'فلوسك في لمحة' })).toBeVisible()
  await expect(page.locator('.metric').filter({ hasText: 'مصروفات الشهر' })).toBeVisible()
  await page.getByRole('banner').getByRole('link', { name: 'Spend' }).click()
  await expect(page.getByRole('heading', { name: 'تابع فلوسك في مكان واحد' })).toBeVisible()
  await page.getByRole('link', { name: 'افتح الرئيسية' }).click()
  await expect(page).toHaveURL('/overview')
  await page.setViewportSize({ width: 1536, height: 900 })
  await expect(page.getByRole('banner').getByRole('button', { name: 'تسجيل الخروج' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 850 })
  await page.locator('.nav-more').click()
  const sidebar = page.getByRole('dialog')
  await sidebar.getByRole('button', { name: 'تسجيل الخروج' }).click()
  await expect(sidebar).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'تسجيل الدخول' })).toBeVisible()
})

