import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'
import { mailLink } from './mailpit'

test('a confirmed account can add, edit and remove purchases without losing history', async ({ page, request }) => {
  test.setTimeout(75_000)
  await page.goto('/purchases')
  await expect(page.getByRole('link', { name: 'Sign in' })).toBeVisible()

  const username = 'purchases_' + Date.now().toString(36)
  const email = username + '@example.test'
  await page.goto('/account/signup')
  await page.getByLabel('Name in Arabic').fill('سلمى')
  await page.getByLabel('Name in English').fill('Salma')
  await page.getByLabel('Username').fill(username)
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password', { exact: true }).fill('Spend-test-2026!')
  await page.getByLabel('Confirm password').fill('Spend-test-2026!')
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByRole('status')).toContainText('will arrive shortly')
  await page.goto(await mailLink(request, email, '/account/confirm'))
  await page.getByRole('button', { name: 'Verify link' }).click()
  await expect(page.getByRole('status')).toHaveText('Email confirmed.')

  await page.goto('/overview')
  await expect(page.locator('.metrics')).toContainText('EGP 0')
  await page.getByRole('link', { name: 'Add purchase' }).click()
  await page.getByRole('button', { name: 'Add purchase', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'Add purchase' })
  await expect(editor).toBeVisible()
  const close = editor.getByRole('button', { name: 'Cancel' })
  await close.focus()
  await expect(editor.getByLabel('What did you buy?')).not.toHaveAttribute('aria-invalid', 'true')
  await close.click()
  await expect(editor).toBeHidden()
  await page.getByRole('button', { name: 'Add purchase', exact: true }).click()
  await page.mouse.click(2, 2)
  await expect(editor).toBeHidden()
  await page.getByRole('button', { name: 'Add purchase', exact: true }).click()
  const form = page.locator('.purchase-entry')
  const log = page.locator('.purchase-log')
  const history = page.locator('.purchase-history')
  const amount = form.getByLabel('Amount (EGP)')

  await form.getByLabel('What did you buy?').fill('Coffee beans')
  await amount.fill('0')
  await amount.blur()
  await expect(amount).toHaveAttribute('aria-invalid', 'true')
  await amount.fill('١٢٣٫٤٥')
  await expect(amount).not.toHaveAttribute('aria-invalid', 'true')
  await form.getByLabel('Category').selectOption('groceries')
  await form.getByLabel('Note (optional)').fill('ملاحظة خاصة')
  await form.getByRole('button', { name: 'Save purchase' }).click()
  const addedToast = page.getByRole('status').filter({ hasText: 'Purchase added' })
  await expect(addedToast).toBeVisible()
  await expect(addedToast).toBeHidden({ timeout: 7000 })
  await expect(log.locator('.purchase-total')).toContainText('123.45')
  await expect(log.getByText('ملاحظة خاصة')).toBeVisible()

  const monthFilter = page.getByRole('button', { name: /^Month ·/ })
  const monthDialog = page.getByRole('dialog', { name: 'Choose a month' })
  const currentMonth = (await log.locator('.purchase-record time').getAttribute('datetime'))!.slice(0, 7)
  const previous = new Date(currentMonth + '-01T00:00:00Z')
  previous.setUTCMonth(previous.getUTCMonth() - 1)
  await monthFilter.click()
  await expect(monthDialog).toBeVisible()
  await page.mouse.click(2, 2)
  await expect(monthDialog).toBeHidden()
  await monthFilter.click()
  await monthDialog.getByLabel('Year').fill(String(previous.getUTCFullYear()))
  await monthDialog.getByRole('button', { name: new Intl.DateTimeFormat('en-EG', { month: 'long', year: 'numeric', timeZone: 'UTC' }).format(previous) }).click()
  await expect(log.getByText('No purchases match these filters.')).toBeVisible()
  await expect(log.locator('.purchase-total')).toContainText('EGP 0')
  await monthFilter.click()
  await monthDialog.getByRole('button', { name: 'This month' }).click()
  await expect(log.getByText('Coffee beans')).toBeVisible()

  await expect(log.getByLabel('Category')).toHaveCount(0)

  await log.getByRole('button', { name: 'Edit purchase' }).click()
  await expect(form.getByLabel('What did you buy?')).toBeFocused()
  await amount.fill('140.75')
  await form.getByRole('button', { name: 'Save purchase' }).click()
  const editedToast = page.locator('#toast-region .app-toast').filter({ hasText: 'Purchase edited' })
  await expect(editedToast.getByRole('status')).toHaveText('Purchase edited')
  await editedToast.getByRole('button', { name: 'Dismiss notification' }).click()
  await expect(editedToast).toBeHidden()
  await expect(log.locator('.purchase-total')).toContainText('140.75')
  const update = history.locator('li').filter({ hasText: 'Purchase edited' })
  await expect(update).toBeHidden()
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await update.getByText('View change').click()
  await expect(update).toContainText('123.45')
  await expect(update).toContainText('140.75')
  await history.getByRole('button', { name: 'Choose a date' }).click()
  const calendar = page.getByRole('dialog', { name: 'Choose a date' })
  await calendar.getByLabel('Year').selectOption('2000')
  await calendar.getByLabel('Month').selectOption('01')
  await calendar.getByRole('button', { name: /^(1 January|January 1,) 2000$/ }).click()
  await expect(history.getByText('No activity in this date range.')).toBeVisible()
  await history.getByRole('button', { name: 'Today', exact: true }).click()
  await expect(update).toBeVisible()

  await page.goto('/overview')
  await expect(page.locator('.metrics')).toContainText('140.75')
  await expect(page.locator('.spending-detail')).toContainText('140.75')
  await expect(page.locator('.purchases')).toContainText('Coffee beans')
  await expect(page.locator('.follow-up')).toContainText('No outstanding debt has a due date.')
  await page.getByRole('link', { name: 'Analytics' }).click()
  await expect(page.locator('.analytics-bars button')).toHaveCount(6)
  await expect(page.locator('.analytics-total')).toContainText('140.75')
  const analyticsPurchases = page.locator('.analytics-purchases')
  const analyticsCategory = analyticsPurchases.getByRole('combobox', { name: 'Category' })
  await analyticsCategory.selectOption('transport')
  await expect(analyticsPurchases.getByText('Coffee beans')).toHaveCount(0)
  await expect(page.locator('.analytics-total')).toContainText('140.75')
  await page.locator('.analytics-categories').getByRole('button', { name: /Groceries/ }).click()
  await expect(analyticsCategory).toHaveValue('groceries')
  await expect(analyticsPurchases.getByText('Coffee beans')).toBeVisible()
  const analyticsMonth = page.getByRole('combobox', { name: 'Month', exact: true })
  await analyticsMonth.selectOption(previous.toISOString().slice(0, 7))
  await expect(page.locator('.analytics-total')).toContainText('EGP 0')
  await expect(page.locator('.analytics-detail').getByText('Coffee beans')).toHaveCount(0)
  await analyticsMonth.selectOption(currentMonth)
  await expect(page.locator('.analytics-total')).toContainText('140.75')
  await page.goto('/overview')
  await page.getByRole('link', { name: 'Add purchase' }).click()

  await page.setViewportSize({ width: 390, height: 850 })
  await page.locator('.language').selectOption('ar')
  await page.locator('.theme-toggle').click()
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl')
  await log.getByRole('button', { name: 'حذف عملية الشراء' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('Coffee beans')
  await expect(dialog.getByRole('button', { name: 'إلغاء' })).toBeFocused()
  await dialog.getByRole('button', { name: 'حذف عملية الشراء' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(log).not.toContainText('Coffee beans')
  await page.getByRole('button', { name: 'السجل', exact: true }).click()
  await expect(history.getByText('الشراء اتحذف · Coffee beans')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(log.locator('.purchase-total')).toContainText('٠')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
})
