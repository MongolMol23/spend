import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'
import { mailLink } from './mailpit'
import { pickDate } from './date-picker'

test('savings goals track deposits, withdrawals, progress, and private history', async ({ page, request }) => {
  test.setTimeout(75_000)
  await page.goto('/savings')
  await expect(page.getByRole('link', { name: 'Sign in' })).toBeVisible()
  const username = 'savings_' + Date.now().toString(36)
  const email = username + '@example.test'
  await page.goto('/account/signup')
  await page.getByLabel('Name in Arabic').fill('سلمى')
  await page.getByLabel('Name in English').fill('Salma')
  await page.getByLabel('Username').fill(username)
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password', { exact: true }).fill('Spend-test-2026!')
  await page.getByLabel('Confirm password').fill('Spend-test-2026!')
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByRole('status')).toContainText('will arrive shortly')
  await page.goto(await mailLink(request, email, '/account/confirm'))
  await page.getByRole('button', { name: 'Verify link' }).click()
  await expect(page.getByRole('status')).toHaveText('Email confirmed.')

  await page.goto('/overview')
  await page.getByRole('link', { name: 'Savings goals' }).click()
  await page.getByRole('button', { name: 'Add goal', exact: true }).click()
  const entry = page.locator('.savings-entry')
  const detail = page.locator('.savings-detail')
  const history = page.locator('.savings-history')
  await entry.getByLabel('Goal name').fill('عجلة')
  await entry.getByLabel('Target amount').fill('١٠٠')
  await pickDate(page, entry.getByRole('button', { name: /^Target date/ }), 'Target date (optional)', '2030-01-15')
  await entry.getByRole('button', { name: 'Save goal' }).click()
  await expect(detail.getByRole('heading', { level: 2 })).toHaveText('عجلة')
  const goalPath = new URL(page.url()).pathname + new URL(page.url()).search
  const movement = detail.getByLabel('Movement type')
  const amount = detail.getByLabel('Amount (EGP)')
  await amount.fill('١٢٠')
  await detail.getByRole('button', { name: 'Record movement' }).click()
  await expect(detail.getByText('Target reached', { exact: true })).toBeVisible()
  await expect(detail.getByRole('progressbar')).toHaveAttribute('value', '10000')

  await movement.selectOption('withdraw')
  await amount.fill('121')
  await detail.getByRole('button', { name: 'Record movement' }).click()
  await expect(page.getByRole('alert')).toContainText('cannot exceed')
  await amount.fill('25.50')
  await detail.getByRole('button', { name: 'Record movement' }).click()
  await expect(detail.getByRole('progressbar')).toHaveAttribute('value', '9450')
  await expect(history).toContainText('Withdrawal recorded')
  await detail.getByRole('button', { name: 'Edit goal' }).click()
  await expect(entry.getByLabel('Goal name')).toBeFocused()
  await entry.getByLabel('Target amount').fill('150')
  await entry.getByRole('button', { name: 'Save goal' }).click()
  await expect(detail.getByRole('progressbar')).toHaveAttribute('max', '15000')
  await expect(history).toContainText('Goal updated')

  await page.goto('/overview')
  await expect(page.locator('.metric').filter({ hasText: 'Spent this month' })).toContainText('EGP 0')
  await expect(page.locator('.savings-overview')).toContainText('94.5')
  await expect(page.locator('.savings-overview')).toContainText('120')
  await expect(page.locator('.savings-overview')).toContainText('25.5')
  await page.goto(goalPath)
  await page.setViewportSize({ width: 390, height: 850 })
  await page.locator('.language').selectOption('ar')
  await page.locator('.theme-toggle').click()
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await detail.getByRole('button', { name: 'أرشفة الهدف' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'تأكيد الأرشفة' }).click()
  await expect(detail.getByText('الهدف اتأرشف', { exact: true })).toBeVisible()
  await expect(detail.locator('.savings-movements li')).toHaveCount(2)
  await expect(page.locator('.savings-list')).toContainText('لسه مفيش أهداف تحويش حالية.')
})
